"""Build lossless reachable transparent-pixel contours; requires Pillow and Node."""
from pathlib import Path
from collections import deque
import hashlib,json,subprocess
from PIL import Image
root=Path(__file__).resolve().parents[1]
metadata_code="""import * as data from './S3_content/src/reviewed-tile-data.js';
const out={};for(const [name,r]of Object.entries(data.REVIEWED_TILE_RULES))if(r.w===1&&r.h===1&&r.kind==='free'&&r.cells[0].sides.some(s=>!s))out[name]=[[.5,.5]];
for(const values of Object.values(data))if(Array.isArray(values))for(const layout of values)if(layout.organicMacro)for(const p of layout.placements||[]){
 const name=p.asset;out[name]||=[];for(const c of layout.centers||[]){
 let x=c[0]-p.x,y=c[1]-p.y,w=p.w,h=p.h;
 for(let i=0;i<(p.turn||0);i++){[w,h]=[h,w];}
 for(let i=0;i<(p.turn||0);i++){[x,y]=[y,w-x];[w,h]=[h,w];}
 if(p.flipY)y=p.h-y;if(p.flipX)x=p.w-x;out[name].push([x,y]);
 }}process.stdout.write(JSON.stringify(out));"""
seeds_by_asset=json.loads(subprocess.run(['node','--input-type=module','-e',metadata_code],cwd=root,text=True,capture_output=True,check=True).stdout)
assets={}
for path in sorted((root/'S3_content/assets').glob('org-*.png')):
    image=Image.open(path).convert('RGBA');w,h=image.size
    if w%54 or h%54: continue
    alpha=image.getchannel('A');transparent={i for i,a in enumerate(alpha.tobytes()) if a==0}
    seeds=[i for i in transparent if i%w in (0,w-1) or i//w in (0,h-1)]
    for cx,cy in seeds_by_asset.get(path.name,[]):
        px,py=int(cx*54),int(cy*54)
        if 0<=px<w and 0<=py<h and py*w+px in transparent:seeds.append(py*w+px)
    seen=set(seeds);queue=deque(seeds)
    while queue:
        i=queue.popleft();x,y=i%w,i//w
        for nx,ny in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
            j=ny*w+nx
            if 0<=nx<w and 0<=ny<h and j in transparent and j not in seen:seen.add(j);queue.append(j)
    # Exact maximal row spans, merged vertically where endpoints match.
    rects=[];active={}
    for y in range(h):
        spans=[];x=0
        while x<w:
            if y*w+x not in seen:x+=1;continue
            start=x
            while x<w and y*w+x in seen:x+=1
            spans.append((start,x))
        current={}
        for span in spans:
            if span in active:rect=active[span];rect[3]+=1
            else:rect=[span[0],y,span[1]-span[0],1];rects.append(rect)
            current[span]=rect
        active=current
    assets[path.name]={'w':w,'h':h,'digest':hashlib.sha256(path.read_bytes()).hexdigest(),'rects':rects}
code="""import clipping from './S3_content/src/vendor/polygon-clipping.js';
let input='';for await(const chunk of process.stdin)input+=chunk;
const data=JSON.parse(input);for(const mask of Object.values(data)){
 const rects=mask.rects.map(([x,y,w,h])=>[[[[x,y],[x+w,y],[x+w,y+h],[x,y+h],[x,y]]]]);
 mask.shape=rects.length?clipping.union(...rects):[];delete mask.rects;
}process.stdout.write(JSON.stringify(data));"""
result=subprocess.run(['node','--input-type=module','-e',code],input=json.dumps(assets),text=True,capture_output=True,cwd=root,check=True)
output=root/'S3_content/src/organic-exploration-data.js'
output.write_text('// Generated by scripts/build-organic-exploration.py. Exact alpha=0 pixels reachable from an artwork edge or declared walkable center.\nexport const ORGANIC_EXPLORATION_MASKS = '+result.stdout+';\n',encoding='utf-8')
print(json.dumps({'assets':len(assets),'bytes':output.stat().st_size}))
