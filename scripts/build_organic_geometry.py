"""Record PNG edge corrections without changing the artist's filenames or images."""
import json
from pathlib import Path
import re

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "S3_content" / "assets"
OUTPUT = ROOT / "S3_content" / "src" / "organic-asset-geometry.js"


def black(pixel):
    r, g, b, a = pixel
    return a > 127 and max(r, g, b) < 64


corrections = {}
for path in sorted(ASSETS.glob("org-*.png")):
    match = re.search(r"NW[ox]NE[ox]SE[ox]SW[ox](N[ox]E[ox]S[ox]W[ox])", path.stem)
    if not match:
        continue
    with Image.open(path) as original:
        image = original.convert("RGBA")
    w, h = image.size
    edges = {
        "N": [image.getpixel((x, 0)) for x in range(w)],
        "E": [image.getpixel((w - 1, y)) for y in range(h)],
        "S": [image.getpixel((x, h - 1)) for x in range(w)],
        "W": [image.getpixel((0, y)) for y in range(h)],
    }
    sides = {side: "o" if sum(map(black, pixels)) > len(pixels) / 2 else "x"
             for side, pixels in edges.items()}
    measured = "".join(side + sides[side] for side in "NESW")
    if measured == match[1]:
        continue
    corners = {corner: "o" if black(image.getpixel(point)) else "x"
               for corner, point in {"NW": (0, 0), "NE": (w - 1, 0),
                                     "SE": (w - 1, h - 1), "SW": (0, h - 1)}.items()}
    corrections[path.name] = "".join(corner + corners[corner] for corner in ("NW", "NE", "SE", "SW")) + measured

OUTPUT.write_text(
    "// Generated by scripts/build_organic_geometry.py from opaque black edge pixels.\n"
    "export const ORGANIC_ASSET_SIGNATURES = Object.freeze("
    + json.dumps(corrections, indent=2) + ");\n",
    encoding="utf-8",
)
print(f"Recorded physical edge corrections for {len(corrections)} organic assets")
